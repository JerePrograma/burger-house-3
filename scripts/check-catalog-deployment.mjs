import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { issueSession,sha256 } from '../backend/auth.ts';
import { normalizePublishedCatalog } from '../lib/catalog-static.ts';
import config from '../frontend.config.json' with { type:'json' };

const url='https://burger-house-3-web.jeremias-j-riv.workers.dev';
const response=await fetch(`${url}/catalog.json`,{cache:'no-store'});
assert.equal(response.status,200);
assert.equal(response.headers.get('cache-control'),'no-store');
assert.equal(response.headers.get('access-control-allow-origin'),'*');
const raw=await response.text(),catalog=normalizePublishedCatalog(JSON.parse(raw));
assert.deepEqual(Object.keys(JSON.parse(raw)).sort(),['config','ingredients','products']);
const editorSecrets=JSON.parse(await readFile(new URL('../.env.catalog-secrets.local.json',import.meta.url),'utf8'));
const token=await issueSession(editorSecrets.SESSION_SECRET);
const editor=await fetch(`${config.publisherUrl}/catalog`,{headers:{Authorization:`Bearer ${token}`}});
assert.equal(editor.status,200);
const editorData=await editor.json();
assert.equal(editorData.revision,await sha256(raw));
assert.equal(editorData.catalog.products.length,catalog.products.length);
const denied=await fetch(`${config.publisherUrl}/catalog`);
assert.equal(denied.status,401);
const management=await fetch(config.managementUrl);
assert.equal(management.status,200);
const login=await fetch(`${config.apiBaseUrl}/admin/login?return_to=${encodeURIComponent(config.managementUrl)}`);
assert.equal(login.status,200);
const backendSecrets=JSON.parse(await readFile(new URL('../.env.backend-secrets.local.json',import.meta.url),'utf8'));
const operational=await fetch(`${config.apiBaseUrl}/api/admin`,{headers:{Authorization:`Bearer ${await issueSession(backendSecrets.SESSION_SECRET)}`,Origin:new URL(config.managementUrl).origin}});
assert.equal(operational.status,200);
const state=await operational.json();
console.log(JSON.stringify({catalog:{status:'publicado',products:catalog.products.length,static:true},editor:{status:'acceso verificado',publishingAvailable:editorData.publishingAvailable},management:{status:'acceso verificado',orders:state.orders.length,products:state.products.length},dataMutations:0},null,2));
